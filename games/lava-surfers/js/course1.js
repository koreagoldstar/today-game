  line(1236, 1264, -4, 4, 5);
  /* 11. 용암 파도가 빨라지는 후반: 섞인 장애물 + 부스터 */
  boosts.push({ s: 1288, u: -3, w: 2.6, l: 4 });
  boosts.push({ s: 1288, u: 3, w: 2.6, l: 4 });
  obs.push({ type: "roll", s: 1320, side: 1, r: 1.8, speed: 10, trigger: 48 });
  obs.push({ type: "fire", s: 1345, u: -3, r: 1.7, period: 2.6, phase: 0, warn: 1.0, on: 1.0 });
  obs.push({ type: "fire", s: 1345, u: 3, r: 1.7, period: 2.6, phase: 0.5, warn: 1.0, on: 1.0 });
