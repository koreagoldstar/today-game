function hash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mulberry32(seed) {
  return function rand() {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function lastHangul(word) {
  const chars = [...String(word)];
  for (let i = chars.length - 1; i >= 0; i -= 1) {
    const code = chars[i].charCodeAt(0);
    if (code >= 0xac00 && code <= 0xd7a3) return chars[i];
  }
  return "";
}

function jongseong(word) {
  const ch = lastHangul(word);
  if (!ch) return 0;
  return (ch.charCodeAt(0) - 0xac00) % 28;
}

function eunNeun(word) {
  return word + (jongseong(word) ? "은" : "는");
}

function iGa(word) {
  return word + (jongseong(word) ? "이" : "가");
}

function eulReul(word) {
  return word + (jongseong(word) ? "을" : "를");
}

function waGwa(word) {
  return word + (jongseong(word) ? "과" : "와");
}

function add(q, correct, wrongs) {
  const question = String(q).trim();
  if (!question || seen.has(question)) return;
  const uniq = [];
  const used = new Set([String(correct)]);
  for (const w of wrongs) {
    const s = String(w);
    if (!s || used.has(s)) continue;
    used.add(s);
    uniq.push(s);
    if (uniq.length >= 3) break;
  }
  if (uniq.length < 3) return;
  const opts = [String(correct), uniq[0], uniq[1], uniq[2]];
  const rand = mulberry32(hash(question) ^ 0x9e3779b9);
  for (let i = opts.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [opts[i], opts[j]] = [opts[j], opts[i]];
  }
  seen.add(question);
  bank.push({ q: question, a: opts, c: opts.indexOf(String(correct)) });
}

function pickOthers(list, keep, n, keyFn) {
  const key = keyFn ? keyFn(keep) : keep;
  return list.filter((item) => (keyFn ? keyFn(item) : item) !== key).slice(0, n);
}

